public class ForDemo {
    public static void main (String[] args) {
        for (int i = 1; i <= 5; i++) {
            System.out.println("Perulangan ke-" + i);
        }
        System.out.println("\n");

        for (int i = 5; i >= 1; i--) {
            System.out.println("Hitung mundur: " + i);
        }
        System.out.println("Selesai!");
    }
}